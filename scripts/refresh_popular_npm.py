#!/usr/bin/env python3
"""
Refreshes app/data/popular_npm_packages.txt: the most-downloaded npm
packages, which Agent 2C's typosquat prefilter compares new dependency
names against (audit P1-11). A new package whose name is within edit
distance 2 of one of these (but isn't one of them) goes to the model.

How: the npm registry's public search API, ranked by popularity, across a
set of broad keywords; every result carries its monthly download count, so
the union is sorted by downloads and the top N are kept. Standard library
only. Run it every few months:

    python scripts/refresh_popular_npm.py            # writes the data file
    python scripts/refresh_popular_npm.py --dry-run  # prints a summary only

If the registry can't be reached, nothing is written. Agent 2C treats a
missing list as "send every new package to the model".
"""
import argparse
import json
import sys
import time
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

SEARCH_URL = "https://registry.npmjs.org/-/v1/search"
OUT = Path(__file__).resolve().parents[1] / "app" / "data" / "popular_npm_packages.txt"
PAGE_SIZE = 250
# The search API needs a query; these broad keywords together cover the
# packages that dominate npm downloads.
KEYWORDS = [
    "javascript", "typescript", "node", "nodejs", "react", "vue", "angular", "svelte", "next", "express",
    "webpack", "babel", "eslint", "prettier", "jest", "test", "testing", "cli", "util", "utility", "utils",
    "http", "https", "request", "fetch", "stream", "fs", "file", "path", "string", "array", "object", "json",
    "promise", "async", "date", "time", "crypto", "hash", "aws", "cloud", "database", "sql", "mongodb",
    "redis", "css", "style", "html", "dom", "browser", "polyfill", "es6", "ecmascript", "lodash", "parser",
    "ast", "compiler", "build", "bundler", "loader", "plugin", "rollup", "vite", "postcss", "sass", "lint",
    "types", "type", "validation", "schema", "logger", "logging", "debug", "color", "terminal", "config",
    "env", "glob", "regex", "url", "server", "framework", "middleware", "auth", "jwt", "oauth", "graphql",
    "api", "sdk", "client", "socket", "websocket", "event", "emitter", "cache", "math", "uuid", "markdown",
    "image", "svg", "animation", "ui", "component", "hooks", "state", "redux", "router", "i18n", "template",
]


def search(keyword: str, offset: int) -> list[dict]:
    query = urllib.parse.urlencode({
        "text": f"keywords:{keyword}", "size": PAGE_SIZE, "from": offset,
        "popularity": "1.0", "quality": "0.0", "maintenance": "0.0",
    })
    with urllib.request.urlopen(f"{SEARCH_URL}?{query}", timeout=30) as res:
        return json.load(res).get("objects", [])


def collect(pages_per_keyword: int) -> dict[str, int]:
    downloads: dict[str, int] = {}
    for keyword in KEYWORDS:
        for page in range(pages_per_keyword):
            objects = search(keyword, page * PAGE_SIZE)
            for obj in objects:
                name = obj["package"]["name"]
                monthly = int((obj.get("downloads") or {}).get("monthly") or 0)
                downloads[name] = max(downloads.get(name, 0), monthly)
            if len(objects) < PAGE_SIZE:
                break
            time.sleep(0.2)  # be polite to the registry
    return downloads


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--top", type=int, default=5000, help="how many names to keep (default 5000)")
    parser.add_argument("--pages", type=int, default=4, help="result pages per keyword (250 each, default 4)")
    parser.add_argument("--dry-run", action="store_true", help="print a summary, don't write the file")
    args = parser.parse_args()

    try:
        downloads = collect(args.pages)
    except Exception as exc:  # network blocked, registry down, ...
        print(f"Could not query the npm registry ({type(exc).__name__}: {exc}); nothing written.", file=sys.stderr)
        return 1
    ranked = sorted(downloads, key=lambda n: (-downloads[n], n))[: args.top]
    if len(ranked) < min(args.top, 1000):
        print(f"Only {len(ranked)} packages found; refusing to write a thin list.", file=sys.stderr)
        return 1

    header = [
        "# Most-downloaded npm packages (monthly downloads, npm registry search API),",
        f"# generated by scripts/refresh_popular_npm.py on {datetime.now(timezone.utc).date().isoformat()}.",
        f"# {len(ranked)} names. Agent 2C's typosquat prefilter (audit P1-11) reads this file.",
    ]
    if args.dry_run:
        print("\n".join(header))
        print("top 20:", ", ".join(ranked[:20]))
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(header + ranked) + "\n")
    print(f"Wrote {len(ranked)} names to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
